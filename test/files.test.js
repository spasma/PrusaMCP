// G-code statistics (ASCII and binary), PrusaSlicer project files, PNG encoding.
import { test } from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";
import { deflateSync, inflateSync } from "node:zlib";
import { parseGCodeStats } from "../build/prusa-cli.js";
import { readBgcodeMetadata } from "../build/bgcode.js";
import { readPrusaProject } from "../build/project-3mf.js";
import { encodePng, crc32 } from "../build/png.js";
import { writeZip, boxObject, model } from "./helpers/zip.js";

function tempFile(name, content) {
  const path = join(mkdtempSync(join(tmpdir(), "prusamcp-files-")), name);
  writeFileSync(path, content);
  return path;
}

/** A bgcode file as libbgcode writes it: header, then blocks with CRC32 checksums. */
function bgcode(blocks) {
  const header = Buffer.alloc(10);
  header.write("GCDE", 0, "ascii");
  header.writeUInt32LE(1, 4);
  header.writeUInt16LE(1, 8); // CRC32 checksums
  const parts = [header];
  for (const { type, compression = 0, text, params, raw } of blocks) {
    const payload = raw ?? Buffer.from(text, "utf-8");
    const data = compression === 1 ? deflateSync(payload) : payload;
    const head = Buffer.alloc(compression ? 12 : 8);
    head.writeUInt16LE(type, 0);
    head.writeUInt16LE(compression, 2);
    head.writeUInt32LE(payload.length, 4);
    if (compression) head.writeUInt32LE(data.length, 8);
    const p = params ?? Buffer.from([0, 0]); // encoding: INI
    const crc = Buffer.alloc(4);
    crc.writeUInt32LE(crc32(Buffer.concat([head, p, data])));
    parts.push(head, p, data, crc);
  }
  return Buffer.concat(parts);
}

test("binary G-code: printer model, time, grams and cost from metadata blocks", async () => {
  const thumbParams = Buffer.alloc(6);
  thumbParams.writeUInt16LE(0, 0); // PNG
  thumbParams.writeUInt16LE(16, 2);
  thumbParams.writeUInt16LE(12, 4);
  const file = bgcode([
    { type: 0, text: "Producer=PrusaSlicer 2.9.7\n" },
    { type: 3, text: "printer_model=COREONE\nlayer_height=0.12\nfilament used [g]=7.28\n" },
    { type: 5, raw: Buffer.from("not really a png"), params: thumbParams },
    { type: 4, compression: 1, text: "filament used [mm]=2382.53\ntotal filament used [g]=7.28\ntotal filament cost=0.20\nestimated printing time (normal mode)=1h 2m 3s\n" },
    { type: 1, compression: 3, raw: Buffer.from([1, 2, 3, 4]) }, // heatshrink G-code: skipped
  ]);

  const meta = readBgcodeMetadata(file);
  assert.equal(meta.printer.get("layer_height"), "0.12");
  assert.equal(meta.thumbnails.length, 1);
  assert.deepEqual([meta.thumbnails[0].format, meta.thumbnails[0].width, meta.thumbnails[0].height], ["png", 16, 12]);

  const stats = await parseGCodeStats(tempFile("a.bgcode", file));
  assert.deepEqual(stats, {
    format: "binary",
    printerModel: "COREONE",
    estimatedTime: "1h 2m 3s",
    estimatedTimeSeconds: 3723,
    filamentUsedMm: 2382.53,
    filamentUsedG: 7.28,
    filamentCost: 0.2,
  });
});

test("ASCII G-code: an empty printer_model does not swallow the next line", async () => {
  const stats = await parseGCodeStats(tempFile("a.gcode", [
    "; filament used [mm] = 1514.58",
    "; total filament used [g] = 4.5",
    "; estimated printing time (normal mode) = 20m 58s",
    "; printer_model =",
    "; printer_notes = something",
  ].join("\n")));
  assert.equal(stats.format, "ascii");
  assert.equal(stats.printerModel, undefined);
  assert.equal(stats.filamentUsedG, 4.5);
  assert.equal(stats.estimatedTimeSeconds, 1258);
});

test("PrusaSlicer project: config, per-object overrides, modifier volumes, thumbnail", async () => {
  const thumbnail = encodePng(2, 2, new Uint8Array(16).fill(200));
  const path = writeZip("project.3mf", {
    "3D/3dmodel.model": model(`<resources>${boxObject(1)}</resources><build><item objectid="1"/></build>`),
    "Metadata/Slic3r_PE.config": "; generated by PrusaSlicer 2.9.7\n\n; layer_height = 0.2\n; printer_model = COREONE\n; start_gcode = M17 ; enable\\nG28\n",
    "Metadata/Slic3r_PE_model.config": `<?xml version="1.0"?><config>
 <object id="1" instances_count="2">
  <metadata type="object" key="name" value="Hoekstuk &amp; co"/>
  <metadata type="object" key="layer_height" value="0.1"/>
  <volume firstid="0" lastid="11"><metadata type="volume" key="volume_type" value="ModelPart"/></volume>
  <volume firstid="12" lastid="23"><metadata type="volume" key="volume_type" value="SupportEnforcer"/></volume>
 </object>
</config>`,
    "Metadata/thumbnail.png": thumbnail,
  });

  const project = await readPrusaProject(path);
  assert.equal(project.config.get("layer_height"), "0.2");
  assert.equal(project.config.get("printer_model"), "COREONE");
  assert.equal(project.config.get("start_gcode"), "M17 ; enable\\nG28");
  assert.deepEqual(project.objects, [
    { name: "Hoekstuk & co", instances: 2, settings: { layer_height: "0.1" }, volumes: { SupportEnforcer: 1 } },
  ]);
  assert.deepEqual(project.thumbnail, thumbnail);
});

test("a 3MF from another program has no project data", async () => {
  const project = await readPrusaProject(writeZip("plain.3mf", {
    "3D/3dmodel.model": model(`<resources>${boxObject(1)}</resources><build><item objectid="1"/></build>`),
  }));
  assert.deepEqual(project, { config: null, thumbnail: null, objects: [] });
});

test("PNG: valid signature, header, and pixels survive a round trip", () => {
  const rgba = new Uint8Array(3 * 2 * 4).map((_, i) => i * 7);
  const png = encodePng(3, 2, rgba);
  assert.deepEqual([...png.subarray(0, 8)], [0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]);
  assert.equal(png.toString("ascii", 12, 16), "IHDR");
  assert.equal(png.readUInt32BE(16), 3);
  assert.equal(png.readUInt32BE(20), 2);
  assert.equal(crc32(Buffer.from("123456789")), 0xcbf43926);

  const idatLength = png.readUInt32BE(33);
  assert.equal(png.toString("ascii", 37, 41), "IDAT");
  const raw = inflateSync(png.subarray(41, 41 + idatLength));
  const rows = [raw.subarray(1, 13), raw.subarray(14, 26)];
  assert.deepEqual(Buffer.concat(rows), Buffer.from(rgba));
});
