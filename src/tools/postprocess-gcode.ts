import { McpServer } from "@modelcontextprotocol/sdk/server/mcp.js";
import { z } from "zod";
import { readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, basename, extname, join } from "node:path";
import { isBgcode } from "../bgcode.js";

export function registerPostprocessGcode(server: McpServer) {
  server.registerTool(
    "postprocess_gcode",
    {
      title: "Post-process G-code",
      description:
        "Edits an existing ASCII G-code file to insert actions: " +
        "a pause at a layer, a filament change (M600), a temperature change " +
        "or a custom command. Writes a new file and leaves the original untouched. " +
        "Binary G-code (.bgcode) is not supported.",
      inputSchema: {
        gcode_path: z.string().describe("Path to the G-code file to modify"),
        actions: z.array(z.object({
          layer: z.number().int().describe("Layer number (starts at 1)"),
          type: z
            .enum(["pause", "color_change", "temperature", "custom"])
            .describe("Action type"),
          value: z
            .string()
            .optional()
            .describe("Value for the type: a temperature (e.g. '220') or a custom G-code command"),
          comment: z.string().optional().describe("Optional comment in the G-code"),
        })).describe("Actions to insert"),
        output_path: z.string().optional().describe("Output path (default: <name>_modified.gcode next to the input); an existing file is overwritten"),
      },
      annotations: {
        title: "Post-process G-code",
        readOnlyHint: false,
        destructiveHint: true,
        idempotentHint: true,
        openWorldHint: false,
      },
    },
    async ({ gcode_path, actions, output_path }) => {
      try {
        if (!existsSync(gcode_path)) {
          return {
            isError: true,
            content: [{ type: "text" as const, text: `File not found: ${gcode_path}` }],
          };
        }

        const raw = await readFile(gcode_path);
        if (isBgcode(raw)) {
          return {
            isError: true,
            content: [{
              type: "text" as const,
              text: 'This is binary G-code (.bgcode). Slice again with slice_prusaslicer gcode_format: "ascii" to post-process it.',
            }],
          };
        }
        const content = raw.toString("utf-8");
        const lines = content.split(/\r?\n/);

        // Find layer change markers in G-code
        // PrusaSlicer uses ";LAYER_CHANGE" or ";BEFORE_LAYER_CHANGE"
        const layerPositions = new Map<number, number>(); // layer number → line index
        let currentLayer = 0;

        for (let i = 0; i < lines.length; i++) {
          const line = lines[i].trim();
          // PrusaSlicer format
          if (line === ";LAYER_CHANGE") {
            currentLayer++;
            layerPositions.set(currentLayer, i);
          }
          // Also check for ";LAYER:N" format (Cura)
          const layerMatch = line.match(/^;LAYER:(\d+)/);
          if (layerMatch) {
            currentLayer = parseInt(layerMatch[1], 10) + 1; // Cura is 0-indexed
            layerPositions.set(currentLayer, i);
          }
        }

        if (layerPositions.size === 0) {
          return {
            isError: true,
            content: [{
              type: "text" as const,
              text: `No layer markers found in the G-code. ` +
                `Was the file generated by PrusaSlicer or Cura?`,
            }],
          };
        }

        // Sort actions by layer (descending) to insert from bottom to top
        const sortedActions = [...actions].sort((a, b) => b.layer - a.layer);
        const insertions: string[] = [];

        for (const action of sortedActions) {
          const lineIndex = layerPositions.get(action.layer);
          if (lineIndex === undefined) {
            insertions.push(`Layer ${action.layer} not found (max: ${layerPositions.size})`);
            continue;
          }

          let gcodeToInsert: string;
          const comment = action.comment ? ` ; ${action.comment}` : "";

          switch (action.type) {
            case "pause":
              gcodeToInsert = [
                `; === PAUSE at layer ${action.layer} (PrusaMCP) ===`,
                `M601${comment}`,  // PrusaSlicer pause
                `; === END PAUSE ===`,
              ].join("\n");
              break;

            case "color_change":
              gcodeToInsert = [
                `; === COLOR CHANGE at layer ${action.layer} (PrusaMCP) ===`,
                `M600${comment}`,  // Filament change
                `; === END COLOR CHANGE ===`,
              ].join("\n");
              break;

            case "temperature":
              const temp = action.value ?? "210";
              gcodeToInsert = [
                `; === TEMP CHANGE at layer ${action.layer} (PrusaMCP) ===`,
                `M104 S${temp}${comment}`,  // Set nozzle temp (no wait)
                `; === END TEMP CHANGE ===`,
              ].join("\n");
              break;

            case "custom":
              gcodeToInsert = [
                `; === CUSTOM at layer ${action.layer} (PrusaMCP) ===`,
                `${action.value ?? ""}${comment}`,
                `; === END CUSTOM ===`,
              ].join("\n");
              break;
          }

          // Insert after the layer marker
          lines.splice(lineIndex + 1, 0, gcodeToInsert);
          insertions.push(`${action.type} @ layer ${action.layer}`);
        }

        // Write output
        // "<name>_modified<ext>": built from the extension, so the input can never be the output by accident.
        const ext = extname(gcode_path);
        const outPath = output_path ??
          join(dirname(gcode_path), `${basename(gcode_path, ext)}_modified${ext || ".gcode"}`);

        await writeFile(outPath, lines.join("\n"), "utf-8");

        const resultLines = [
          `## G-code modified`,
          `**File**: ${outPath}`,
          `**Total layers**: ${layerPositions.size}`,
          `**Actions inserted**: ${insertions.length}`,
          "",
          ...insertions.map((s) => `- ${s}`),
        ];

        return {
          content: [{ type: "text" as const, text: resultLines.join("\n") }],
        };
      } catch (error) {
        return {
          isError: true,
          content: [{
            type: "text" as const,
            text: `Error: ${error instanceof Error ? error.message : String(error)}`,
          }],
        };
      }
    },
  );
}
